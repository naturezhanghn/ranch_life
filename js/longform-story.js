function chapterForDay(day) {
  return LONGFORM_CHAPTERS.find((chapter) => day >= chapter.range[0] && day <= chapter.range[1])
    || LONGFORM_CHAPTERS[LONGFORM_CHAPTERS.length - 1];
}

export function getLongformStoryBeat(state) {
  const day = Math.max(1, Number(state?.day) || 1);
  const chapter = chapterForDay(day);
  const index = day > chapter.range[1]
    ? (day - chapter.range[1] - 1) % chapter.beats.length
    : Math.min(chapter.beats.length - 1, Math.max(0, day - chapter.range[0]));
  const choice = chapter.choices.find((entry) => entry.day === day) || null;
  const choiceKey = choice ? `${day}:${choice.id}` : null;
  const selectedId = choiceKey ? state?.story?.longform?.choices?.[choiceKey] : null;
  return {
    chapter,
    day,
    title: chapter.title,
    setting: chapter.setting,
    cast: chapter.cast,
    text: chapter.beats[index],
    choice: choice && !selectedId ? choice : null,
    selectedChoice: choice && selectedId === choice.id ? choice : null,
    progress: `${day} / ${LONGFORM_STORY_SPEC.plannedDays}`,
  };
}

export function getLongformChapterProgress(state) {
  const beat = getLongformStoryBeat(state);
  const [start, end] = beat.chapter.range;
  const day = Math.max(start, Math.min(end, beat.day));
  return {
    chapter: beat.chapter,
    current: day - start + 1,
    total: end - start + 1,
  };
}
